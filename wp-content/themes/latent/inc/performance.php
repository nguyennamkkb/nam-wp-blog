<?php
/**
 * Performance tuning for the Latent theme.
 *
 * Keeps the theme markup contract intact while giving the browser better
 * loading hints: correct `sizes` for card/featured images, eager loading for
 * the hero image, a matching preload on single posts, async decoding for
 * every attachment image and removal of the unused core emoji bundle.
 *
 * @package latent
 */

declare(strict_types=1);

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Returns the responsive `sizes` value for a featured-image block.
 *
 * The layout classes are owned by the theme; an unknown class returns an
 * empty string so the filter leaves the block untouched.
 *
 * @param string $class_name Block class name.
 * @return string
 */
function latent_performance_featured_sizes( string $class_name ): string {
	if ( str_contains( $class_name, 'latent-card__media' ) ) {
		return '(max-width: 640px) 100vw, (max-width: 1024px) 50vw, 384px';
	}

	if ( str_contains( $class_name, 'latent-featured__media' ) ) {
		return '(max-width: 900px) 100vw, 480px';
	}

	return '';
}

/**
 * Applies responsive sizing and loading hints to featured-image blocks.
 *
 * Cards are always lazy and never compete with the hero for bandwidth. The
 * hero image is eager and high priority so it can become the LCP element as
 * early as possible. Only attributes are changed; the element structure and
 * the `srcset` URLs generated by core are preserved.
 *
 * @param string               $block_content Rendered block HTML.
 * @param array<string, mixed> $block         Parsed block data.
 * @return string
 */
function latent_performance_render_featured_image( string $block_content, array $block ): string {
	if ( '' === trim( $block_content ) ) {
		return $block_content;
	}

	// Parent blocks receive the filter too; only touch the image block itself.
	if ( ! isset( $block['blockName'] ) || 'core/post-featured-image' !== $block['blockName'] ) {
		return $block_content;
	}

	$attrs      = isset( $block['attrs'] ) && is_array( $block['attrs'] ) ? $block['attrs'] : array();
	$class_name = isset( $attrs['className'] ) && is_string( $attrs['className'] ) ? $attrs['className'] : '';

	// Fall back to the rendered class if the block data omits the attribute.
	if ( '' === $class_name ) {
		if ( str_contains( $block_content, 'latent-card__media' ) ) {
			$class_name = 'latent-card__media';
		} elseif ( str_contains( $block_content, 'latent-featured__media' ) ) {
			$class_name = 'latent-featured__media';
		}
	}

	$sizes = latent_performance_featured_sizes( $class_name );

	if ( '' === $sizes ) {
		return $block_content;
	}

	$is_card   = str_contains( $class_name, 'latent-card__media' );
	$processor = new WP_HTML_Tag_Processor( $block_content );

	if ( ! $processor->next_tag( array( 'tag_name' => 'IMG' ) ) ) {
		return $block_content;
	}

	$processor->set_attribute( 'sizes', $sizes );

	if ( $is_card ) {
		$processor->set_attribute( 'loading', 'lazy' );
		// A lazy image must not keep the high fetch priority core assigns to
		// the first image on the page.
		$processor->remove_attribute( 'fetchpriority' );
	} else {
		$processor->set_attribute( 'loading', 'eager' );
		$processor->set_attribute( 'fetchpriority', 'high' );
	}

	return $processor->get_updated_html();
}
add_filter( 'render_block', 'latent_performance_render_featured_image', 10, 2 );

/**
 * Prints an image preload that mirrors a rendered attachment image.
 *
 * The `full` source is used for the fallback `href`, while `imagesrcset` and
 * `imagesizes` describe the candidate the browser will actually pick. Keeping
 * the same pair as the visible image avoids downloading the largest file twice
 * on small screens.
 *
 * @param int    $attachment_id Attachment ID.
 * @param string $sizes         Responsive sizes value used by the image.
 * @return void
 */
function latent_performance_print_image_preload( int $attachment_id, string $sizes ): void {
	$src = wp_get_attachment_image_url( $attachment_id, 'full' );

	if ( ! is_string( $src ) || '' === $src ) {
		return;
	}

	$srcset = wp_get_attachment_image_srcset( $attachment_id, 'full' );
	$tag    = '<link rel="preload" as="image" href="' . esc_url( $src ) . '"';

	if ( is_string( $srcset ) && '' !== $srcset ) {
		$tag .= ' imagesrcset="' . esc_attr( $srcset ) . '"';
	}

	if ( '' !== $sizes ) {
		$tag .= ' imagesizes="' . esc_attr( $sizes ) . '"';
	}

	$tag .= ' fetchpriority="high">' . "\n";

	echo $tag; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- URL and attributes are escaped above.
}

/**
 * Preloads the single-post featured image.
 *
 * The core post-featured-image block renders the full-size URL on the single
 * template, so the preload uses the same `full` source and the sizes value the
 * block emits.
 *
 * @return void
 */
function latent_performance_preload_featured_image(): void {
	if ( ! is_singular( 'post' ) ) {
		return;
	}

	$post_id = (int) get_queried_object_id();

	if ( $post_id <= 0 || ! has_post_thumbnail( $post_id ) ) {
		return;
	}

	$attachment_id = (int) get_post_thumbnail_id( $post_id );
	latent_performance_print_image_preload(
		$attachment_id,
		(string) wp_get_attachment_image_sizes( $attachment_id, 'full' )
	);
}
add_action( 'wp_head', 'latent_performance_preload_featured_image', 2 );

/**
 * Preloads the front-page hero image.
 *
 * The front-page template renders the latest post through a one-item query and
 * marks that image as the eager, high-priority hero. Preloading it starts the
 * request before the query loop has rendered, which shortens the LCP resource
 * load delay without changing the template or markup.
 *
 * @return void
 */
function latent_performance_preload_front_image(): void {
	if ( ! is_front_page() || 'page' !== get_option( 'show_on_front' ) ) {
		return;
	}

	$latest = get_posts(
		array(
			'post_type'           => 'post',
			'post_status'         => 'publish',
			'posts_per_page'      => 1,
			'orderby'             => 'date',
			'order'               => 'DESC',
			'no_found_rows'       => true,
			'ignore_sticky_posts' => true,
		)
	);

	if ( ! isset( $latest[0] ) || ! has_post_thumbnail( $latest[0] ) ) {
		return;
	}

	latent_performance_print_image_preload(
		(int) get_post_thumbnail_id( $latest[0] ),
		'(max-width: 900px) 100vw, 480px'
	);
}
add_action( 'wp_head', 'latent_performance_preload_front_image', 2 );

/**
 * Adds async decoding to attachment images that do not declare one.
 *
 * @param array<string, string> $attr Image attributes.
 * @return array<string, string>
 */
function latent_performance_image_decoding( array $attr ): array {
	if ( empty( $attr['decoding'] ) ) {
		$attr['decoding'] = 'async';
	}

	return $attr;
}
add_filter( 'wp_get_attachment_image_attributes', 'latent_performance_image_decoding' );

/**
 * Defers the author avatar and other non-critical avatars.
 *
 * The author box sits far below the fold on single posts, but core renders its
 * Gravatar eagerly. Loading it lazily keeps the external request out of the
 * initial viewport and prevents the avatar box from participating in layout
 * shifts while the page is still settling.
 *
 * @param string $avatar      Avatar HTML.
 * @param mixed  $id_or_email User identifier.
 * @param int    $size        Avatar size in pixels.
 * @return string
 */
function latent_performance_avatar_attributes( string $avatar, mixed $id_or_email, int $size ): string {
	unset( $id_or_email, $size );

	if ( ! str_contains( $avatar, '<img' ) ) {
		return $avatar;
	}

	$processor = new WP_HTML_Tag_Processor( $avatar );

	if ( ! $processor->next_tag( array( 'tag_name' => 'IMG' ) ) ) {
		return $avatar;
	}

	if ( null === $processor->get_attribute( 'loading' ) ) {
		$processor->set_attribute( 'loading', 'lazy' );
	}

	if ( null === $processor->get_attribute( 'fetchpriority' ) ) {
		$processor->set_attribute( 'fetchpriority', 'low' );
	}

	return $processor->get_updated_html();
}
add_filter( 'get_avatar', 'latent_performance_avatar_attributes', 10, 3 );

/**
 * Removes the core emoji detection script and styles.
 *
 * The design does not use WordPress emoji replacements, so the inline script,
 * its inline CSS and the related feed/mail filters are dead weight on every
 * request.
 *
 * @return void
 */
function latent_performance_disable_emoji(): void {
	remove_action( 'wp_head', 'print_emoji_detection_script', 7 );
	remove_action( 'embed_head', 'print_emoji_detection_script' );
	remove_action( 'wp_enqueue_scripts', 'wp_enqueue_emoji_styles' );
	remove_action( 'wp_print_styles', 'print_emoji_styles' );
	remove_action( 'admin_print_scripts', 'print_emoji_detection_script' );
	remove_action( 'admin_print_styles', 'print_emoji_styles' );
	remove_action( 'enqueue_embed_scripts', 'wp_enqueue_emoji_styles' );

	remove_filter( 'the_content_feed', 'wp_staticize_emoji' );
	remove_filter( 'comment_text_rss', 'wp_staticize_emoji' );
	remove_filter( 'wp_mail', 'wp_staticize_emoji_for_email' );
	remove_filter( 'tiny_mce_plugins', 'disable_emojis_tinymce' );
}
add_action( 'init', 'latent_performance_disable_emoji' );
